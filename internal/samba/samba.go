// Package samba generates the managed smb.conf, controls the smbd process and
// keeps Samba users in sync with the application configuration.
package samba

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"sync"
	"time"

	"github.com/tommilevs/keenetic-smb-ui/internal/acl"
	"github.com/tommilevs/keenetic-smb-ui/internal/config"
)

// Manager owns the private Samba instance (separate config, pid and state dirs
// so the native NDMS SMB service is never touched).
type Manager struct {
	mu  sync.Mutex
	cfg *config.Config
}

// New returns a manager bound to the live configuration.
func New(cfg *config.Config) *Manager { return &Manager{cfg: cfg} }

// Config renders smb.conf for the current settings.
func (m *Manager) Config() string {
	m.mu.Lock()
	defer m.mu.Unlock()
	return Render(m.cfg)
}

// Render builds the smb.conf text for cfg. Exported for tests and for the UI
// "preview" view.
func Render(cfg *config.Config) string {
	s := cfg.SMB
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by keenetic-smb-ui — do not edit by hand\n")
	fmt.Fprintf(&b, "[global]\n")
	fmt.Fprintf(&b, "   workgroup = %s\n", s.Workgroup)
	fmt.Fprintf(&b, "   server string = %s\n", s.ServerString)
	fmt.Fprintf(&b, "   netbios name = %s\n", firstLabel(s.ServerString))
	fmt.Fprintf(&b, "   server role = standalone server\n")
	fmt.Fprintf(&b, "   security = user\n")
	fmt.Fprintf(&b, "   map to guest = never\n")
	fmt.Fprintf(&b, "   passdb backend = tdbsam\n")
	fmt.Fprintf(&b, "   server min protocol = %s\n", orDefault(s.MinProtocol, "SMB2"))
	fmt.Fprintf(&b, "   server max protocol = %s\n", orDefault(s.MaxProtocol, "SMB3_11"))
	fmt.Fprintf(&b, "   interfaces = %s\n", s.ListenIP)
	fmt.Fprintf(&b, "   bind interfaces only = yes\n")
	fmt.Fprintf(&b, "   smb ports = %s\n", orDefault(s.Ports, "445"))
	fmt.Fprintf(&b, "   log file = /opt/var/keenetic-smb-ui/log/samba.log\n")
	fmt.Fprintf(&b, "   max log size = 1024\n")
	fmt.Fprintf(&b, "   load printers = no\n")
	fmt.Fprintf(&b, "   printing = bsd\n")
	fmt.Fprintf(&b, "   disable spoolss = yes\n")
	fmt.Fprintf(&b, "   dns proxy = no\n")
	fmt.Fprintf(&b, "   unix charset = UTF-8\n")
	fmt.Fprintf(&b, "   unix extensions = no\n")
	fmt.Fprintf(&b, "   server signing = auto\n")
	fmt.Fprintf(&b, "   server multi channel support = yes\n")
	fmt.Fprintf(&b, "   strict allocate = no\n")
	fmt.Fprintf(&b, "   aio read size = 0\n")
	fmt.Fprintf(&b, "   aio write size = 0\n")
	fmt.Fprintf(&b, "   use sendfile = yes\n")
	fmt.Fprintf(&b, "   state directory = /opt/var/keenetic-smb-ui/state\n")
	fmt.Fprintf(&b, "   cache directory = /opt/var/keenetic-smb-ui/cache\n")
	fmt.Fprintf(&b, "   lock directory = /opt/var/keenetic-smb-ui/lock\n")
	fmt.Fprintf(&b, "   pid directory = %s\n", orDefault(cfg.Paths.SambaPidDir, "/opt/var/keenetic-smb-ui/run"))
	fmt.Fprintf(&b, "   private dir = /opt/etc/samba/private\n")
	for _, opt := range s.ExtraOptions {
		if strings.TrimSpace(opt) == "" {
			continue
		}
		fmt.Fprintf(&b, "   %s\n", opt)
	}
	fmt.Fprintf(&b, "\n[%s]\n", orDefault(s.ShareName, "all"))
	fmt.Fprintf(&b, "   path = %s\n", orDefault(s.SharePath, "/opt/var/keenetic-smb-ui/share"))
	fmt.Fprintf(&b, "   comment = aggregated storage\n")
	fmt.Fprintf(&b, "   browseable = yes\n")
	fmt.Fprintf(&b, "   read only = %s\n", yesNo(s.ShareReadOnly))
	if s.ForceUser {
		// Aggregated tree mixes root-owned CIFS mounts and router disks; Samba
		// must act as root there or ordinary Samba users cannot write.
		fmt.Fprintf(&b, "   force user = root\n")
		fmt.Fprintf(&b, "   force group = root\n")
	}
	fmt.Fprintf(&b, "   guest ok = %s\n", yesNo(cfg.SMB.GuestOK))
	fmt.Fprintf(&b, "   follow symlinks = yes\n")
	fmt.Fprintf(&b, "   wide links = yes\n")
	fmt.Fprintf(&b, "   create mask = 0664\n")
	fmt.Fprintf(&b, "   directory mask = 0775\n")
	users := enabledUsers(cfg)
	if len(users) > 0 && !cfg.SMB.GuestOK {
		// When folder ACLs exist, the aggregate share is limited to users who
		// may at least read the share root; everybody else reaches the tree
		// through their own folder shares below.
		if len(cfg.Folders) > 0 {
			rootUsers := acl.Readers(cfg.Folders, "", users)
			if len(rootUsers) > 0 {
				fmt.Fprintf(&b, "   valid users = %s\n", strings.Join(rootUsers, " "))
			} else {
				fmt.Fprintf(&b, "   valid users = %s\n", strings.Join(users, " "))
			}
		} else {
			fmt.Fprintf(&b, "   valid users = %s\n", strings.Join(users, " "))
		}
	}
	renderFolders(&b, cfg, users)
	return b.String()
}

// renderFolders emits one Samba share per folder that has an ACL, using
// "read only = yes" plus an explicit "write list" to express per-user rights.
func renderFolders(b *strings.Builder, cfg *config.Config, users []string) {
	if len(cfg.Folders) == 0 {
		return
	}
	root := strings.TrimRight(orDefault(cfg.SMB.SharePath, "/opt/var/keenetic-smb-ui/share"), "/")
	mainShare := orDefault(cfg.SMB.ShareName, "all")
	seen := map[string]bool{mainShare: true}
	for _, f := range cfg.Folders {
		if !f.Enabled {
			continue
		}
		// The share root is expressed by the main [all] section above: its
		// valid users are already computed from the root folder ACL.
		if acl.CleanPath(f.Path) == "" {
			continue
		}
		readers := acl.Readers(cfg.Folders, f.Path, users)
		if len(readers) == 0 {
			continue
		}
		writers := acl.Writers(cfg.Folders, f.Path, users)
		name := acl.ShareName(f)
		if seen[name] {
			name += "-2"
		}
		seen[name] = true
		dir := root
		if p := acl.CleanPath(f.Path); p != "" {
			dir += "/" + p
		}
		fmt.Fprintf(b, "\n[%s]\n", name)
		fmt.Fprintf(b, "   path = %s\n", dir)
		fmt.Fprintf(b, "   comment = folder ACL (%s)\n", acl.CleanPath(f.Path))
		fmt.Fprintf(b, "   browseable = yes\n")
		fmt.Fprintf(b, "   read only = yes\n")
		fmt.Fprintf(b, "   valid users = %s\n", strings.Join(readers, " "))
		if len(writers) > 0 {
			fmt.Fprintf(b, "   write list = %s\n", strings.Join(writers, " "))
		}
		if cfg.SMB.ForceUser {
			fmt.Fprintf(b, "   force user = root\n")
			fmt.Fprintf(b, "   force group = root\n")
		}
		fmt.Fprintf(b, "   follow symlinks = yes\n")
		fmt.Fprintf(b, "   wide links = yes\n")
		fmt.Fprintf(b, "   create mask = 0664\n")
		fmt.Fprintf(b, "   directory mask = 0775\n")
	}
}

func enabledUsers(cfg *config.Config) []string {
	out := make([]string, 0, len(cfg.SMB.Users))
	for _, u := range cfg.SMB.Users {
		if u.Enabled && u.Name != "" {
			out = append(out, u.Name)
		}
	}
	return out
}

func firstLabel(s string) string {
	if i := strings.IndexAny(s, " ."); i > 0 {
		return s[:i]
	}
	return s
}

func orDefault(v, def string) string {
	if strings.TrimSpace(v) == "" {
		return def
	}
	return v
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

// WriteConfig renders and stores smb.conf.
func (m *Manager) WriteConfig() error {
	path := m.cfg.Paths.SambaConf
	if path == "" {
		path = "/opt/etc/keenetic-smb-ui/smb.conf"
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	for _, d := range []string{
		"/opt/var/keenetic-smb-ui/state",
		"/opt/var/keenetic-smb-ui/cache",
		"/opt/var/keenetic-smb-ui/lock",
		"/opt/var/run/samba",
		"/opt/var/run/samba/ncalrpc",
		"/opt/var/lock/samba",
		"/opt/var/log/samba",
		m.cfg.Paths.SambaPidDir,
		"/opt/etc/samba/private",
		"/opt/var/keenetic-smb-ui/log",
		orDefault(m.cfg.SMB.SharePath, "/opt/var/keenetic-smb-ui/share"),
	} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(path, []byte(Render(m.cfg)), 0o600)
}

// SyncUsers creates/updates Samba users from the config.
func (m *Manager) SyncUsers() error {
	conf := m.cfg.Paths.SambaConf
	if conf == "" {
		conf = "/opt/etc/keenetic-smb-ui/smb.conf"
	}
	for _, u := range m.cfg.SMB.Users {
		if u.Name == "" || !u.Enabled || u.Password == "" {
			continue
		}
		// Samba needs a matching unix account for tdbsam entries on Entware.
		if exec.Command("id", "-u", u.Name).Run() != nil {
			if out, err := exec.Command("adduser", "-D", "-H", "-s", "/bin/false", u.Name).CombinedOutput(); err != nil {
				return fmt.Errorf("adduser %s: %v: %s", u.Name, err, strings.TrimSpace(string(out)))
			}
		}
		cmd := exec.Command("smbpasswd", "-c", conf, "-a", "-s", u.Name)
		cmd.Stdin = bytes.NewBufferString(u.Password + "\n" + u.Password + "\n")
		if out, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("smbpasswd %s: %v: %s", u.Name, err, strings.TrimSpace(string(out)))
		}
	}
	return nil
}

// Start launches smbd detached from the app process.
func (m *Manager) Start() error {
	if m.running() {
		return nil
	}
	_ = os.Remove(filepath.Join(m.cfg.Paths.SambaPidDir, "smbd.pid"))
	if err := m.WriteConfig(); err != nil {
		return err
	}
	conf := m.cfg.Paths.SambaConf
	cmd := exec.Command("smbd", "-D", "--configfile", conf)
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("smbd start: %v: %s", err, strings.TrimSpace(string(out)))
	}
	for i := 0; i < 50; i++ {
		if m.running() {
			return nil
		}
		time.Sleep(100 * time.Millisecond)
	}
	return fmt.Errorf("smbd did not start (see %s)", "/opt/var/keenetic-smb-ui/log/samba.log")
}

// Stop terminates the managed smbd (pid file of the private instance).
func (m *Manager) Stop() error {
	pidFile := filepath.Join(m.cfg.Paths.SambaPidDir, "smbd.pid")
	data, err := os.ReadFile(pidFile)
	if err != nil {
		return nil
	}
	pid := strings.TrimSpace(string(data))
	if pid == "" {
		_ = os.Remove(pidFile)
		return nil
	}
	_ = exec.Command("kill", "-TERM", pid).Run()
	// wait for the process to disappear so Start() cannot see a zombie pid
	for i := 0; i < 50; i++ {
		if exec.Command("kill", "-0", pid).Run() != nil {
			break
		}
		time.Sleep(100 * time.Millisecond)
	}
	_ = os.Remove(pidFile)
	return nil
}

// Restart stops and starts the managed instance.
func (m *Manager) Restart() error {
	_ = m.Stop()
	return m.Start()
}

// running reports whether the managed smbd pid file points at a live process.
func (m *Manager) running() bool {
	pidFile := filepath.Join(m.cfg.Paths.SambaPidDir, "smbd.pid")
	data, err := os.ReadFile(pidFile)
	if err != nil {
		return false
	}
	pid := strings.TrimSpace(string(data))
	if pid == "" {
		return false
	}
	return exec.Command("kill", "-0", pid).Run() == nil
}

// Status returns a human-readable status line for the UI.
func (m *Manager) Status() string {
	if !m.cfg.SMB.Enabled {
		return "disabled"
	}
	if m.running() {
		return "running"
	}
	return "stopped"
}

// EnsureBindIP adds the configured IP to the bind interface when missing.
func (m *Manager) EnsureBindIP() (bool, error) {
	ip, dev := m.cfg.SMB.ListenIP, m.cfg.SMB.BindDevice
	if ip == "" || dev == "" {
		return false, nil
	}
	out, err := exec.Command("ip", "-4", "addr", "show", "dev", dev).Output()
	if err != nil {
		return false, err
	}
	if strings.Contains(string(out), ip+"/") {
		return false, nil
	}
	if err := exec.Command("ip", "addr", "add", ip+"/32", "dev", dev).Run(); err != nil {
		return false, fmt.Errorf("ip addr add %s dev %s: %w", ip, dev, err)
	}
	return true, nil
}
